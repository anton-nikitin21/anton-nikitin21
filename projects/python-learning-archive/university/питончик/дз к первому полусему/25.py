import random
# Импортируем модуль random для генерации случайных чисел


def in_region(x, y):
    # Функция проверяет, принадлежит ли точка (x, y) заданной области.
    # Возвращает True, если точка удовлетворяет всем условиям области.
    return (2 * x * x + y**3 < 2) and (x - y < 1) and (-2 < x < 2) and (-2 < y < 2)


def area_monte_carlo(samples=200_000, seed=42):
    # Функция оценивает площадь области методом Монте-Карло.
    # samples — количество случайных точек для генерации
    # seed — фиксирует начальное состояние генератора для воспроизводимости

    random.seed(seed)  # Устанавливаем зерно генератора случайных чисел
    inside = 0  # Счётчик точек, попавших внутрь области

    # Область ограничена прямоугольником [-2, 2] x [-2, 2],
    # площадь которого равна 16 (4 * 4).
    for _ in range(samples):
        # Генерируем случайную точку (x, y) внутри квадрата [-2, 2] x [-2, 2]
        x = random.uniform(-2, 2)
        y = random.uniform(-2, 2)

        # Проверяем, попадает ли точка в заданную область
        if in_region(x, y):
            inside += 1  # Увеличиваем счётчик точек внутри области

    # Вычисляем долю точек, попавших внутрь области
    fraction = inside / samples

    # Площадь прямоугольника, в котором проводились испытания
    box_area = 4 * 4  # (2 - (-2)) * (2 - (-2)) = 16

    # Оценка площади области: доля попаданий × площадь прямоугольника
    estimated_area = fraction * box_area

    # Возвращаем приближённую площадь
    return estimated_area


# Пример использования
if __name__ == "__main__":
    est = area_monte_carlo(200_000, seed=1)
    # Вызываем функцию с 200 000 случайных точек и фиксированным seed
    print(f"Приближённая площадь (Монте-Карло): {est:.5f}")
    # Выводим приближённое значение площади с 5 знаками после запятой