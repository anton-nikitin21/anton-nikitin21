import datetime
def sort_dict(d):
    all_visits = []
    # Создаем пустой список all_visits для хранения всех записей в формате (время, пользователь)

    # Собираем все записи в один список
    for user, times in d.items():
        # Проходим по каждой паре ключ-значение в словаре
        # user — имя пользователя, times — список его времен входа
        for t in times:
            # Проходим по каждому времени входа пользователя
            all_visits.append((t, user))
            # Добавляем кортеж (время, пользователь) в список all_visits

    # Сортируем список по времени входа
    all_visits.sort(key=lambda x: x[0])
    # Используем ключ сортировки x[0], чтобы сортировать по первому элементу кортежа (время)

    # Выводим пользователей в порядке времени
    for _, user in all_visits:
        # Проходим по отсортированному списку
        print(user, end=' ')
        # Выводим имя пользователя через пробел, игнорируя время (_)


# Пример использования:
d = {
'Арлекин': [datetime.datetime(2017, 3, 5, 12, 30, 10), datetime.datetime(2018, 2, 6, 11, 40, 10)],
'Пьеро': [datetime.datetime(2018, 1, 1, 9, 30, 50)],
'Мальвина': [datetime.datetime(2019, 3, 4, 18, 46, 12)],
'Карабас': [datetime.datetime(2017, 3, 8, 12, 30, 10), datetime.datetime(2017, 3, 5, 14, 30, 10)]
}
sort_dict(d)
# Ожидаемый вывод: Арлекин Карабас Карабас Пьеро Арлекин Мальвина
