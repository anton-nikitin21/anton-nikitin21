def count_glas(texts):
    # Задаем строку со всеми русскими гласными буквами
    glas = 'аеёиоуыэюя'

    # Создаем словарь, где каждому гласному соответствует начальное значение 0
    result = {ch: 0 for ch in glas}

    # Перебираем каждый символ в тексте
    for char in texts:
        # Проверяем, является ли символ буквой и гласной
        if char.isalpha() and char.lower() in result:
            # Если да — увеличиваем счетчик этой буквы на 1
            result[char.lower()] += 1

    # Возвращаем словарь с количеством каждой гласной
    return result


# Просим пользователя ввести предложение
text = input("Введите предложение: ")

# Выводим результат — словарь с количеством гласных
print(count_glas(text))


# -----------------------------------------
# АНАЛИЗ СЛОЖНОСТИ:
#
# Пусть n — длина строки (количество символов во входном тексте)
#
# Временная сложность:
# - Перебор всех символов строки — O(n)
# - Проверка `char.isalpha()` и `char.lower() in result` — O(1), так как доступ к словарю по ключу выполняется за константное время.
# → Итого: O(n)
#
# Пространственная сложность:
# - Словарь `result` всегда фиксированного размера (10 гласных), не зависит от n → O(1)
# - Дополнительная память для переменных незначительна.
# → Итого: O(1)
