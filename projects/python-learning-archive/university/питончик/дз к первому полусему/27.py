def fibonacci(n):
    # Функция возвращает список из первых n чисел Фибоначчи

    if n <= 0:
        return []
        # Если пользователь ввёл 0 или отрицательное число — возвращаем пустой список

    elif n == 1:
        return [0]
        # Если нужно одно число — возвращаем список с первым числом Фибоначчи (0)

    elif n == 2:
        return [0, 1]
        # Если нужно два числа — возвращаем список с первыми двумя числами Фибоначчи

    # Для n > 2 создаём список с первыми двумя числами
    fib = [0, 1]

    # Генерация остальных чисел Фибоначчи
    for i in range(2, n):
        fib.append(fib[-1] + fib[-2])
        # Каждое новое число — сумма двух последних чисел в списке

    return fib
    # Возвращаем список из n чисел Фибоначчи

N = int(input("Введите количество чисел Фибоначчи: "))
print(f"Первые {N} чисел Фибоначчи:", fibonacci(N))

