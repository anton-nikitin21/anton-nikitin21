def find_median_sorted_arrays(nums1, nums2):
    m, n = len(nums1), len(nums2)                # Длины входных массивов
    total_len = m + n                            # Общая длина после объединения

    # Позиции медианы (одна или две — в зависимости от чётности)
    median_pos1 = (total_len - 1) // 2           # Левая медианная позиция
    median_pos2 = total_len // 2                 # Правая медианная позиция

    i = j = 0                                     # Индексы в nums1 и nums2
    prev = curr = 0                               # Два последних значения при проходе

    # Объединённый проход — как в merge-сортировке
    for k in range(total_len):
        # Выбираем наименьшее доступное значение
        if i < m and (j >= n or nums1[i] <= nums2[j]):
            val = nums1[i]
            i += 1
        else:
            val = nums2[j]
            j += 1

        prev, curr = curr, val  # Сохраняем два последних значения (для медианы)

        # После достижения позиции второй медианы можно остановиться
        if k == median_pos2:
            break

    # Если общее количество элементов нечётное → медиана = текущее значение
    if total_len % 2 == 1:
        return float(curr)
    else:
        # Иначе берём среднее из двух центральных значений
        return (prev + curr) / 2

# -----------------------------------------
# АНАЛИЗ СЛОЖНОСТИ:
#
# Пусть:
#   m = len(nums1)
#   n = len(nums2)
#
# Временная сложность:
# - Мы выполняем проход по первым (m + n) // 2 + 1 элементам
# - Каждая операция — O(1)
# → Итого: O(m + n)
#
# Пространственная сложность:
# - Используется только постоянное количество переменных
# → Итого: O(1)
# -----------------------------------------
