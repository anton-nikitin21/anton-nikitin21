# - Максимальное количество итераций цикла while ограничено количеством символов в римской записи числа,
#   которое не превышает примерно 15-20 (константа)
# - Конкатенация строк в Python занимает O(k), где k — текущая длина строки,
#   но длина результата ограничена константой
# → Итого: O(1) — константное время
#
# Пространственная сложность:
# - Итоговая строка занимает O(1) память, так как длина римской записи ограничена
