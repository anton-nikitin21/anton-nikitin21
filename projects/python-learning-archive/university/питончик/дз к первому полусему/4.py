
def min_edit_distance(word1, word2):
    # Определяем длины двух слов
    m, n = len(word1), len(word2)

    # Приводим оба слова к нижнему регистру, чтобы сравнение не зависело от регистра
    word1, word2 = word1.lower(), word2.lower()

    # Создаем двумерную таблицу dp (m+1) x (n+1)
    # dp[i][j] — минимальное количество операций, чтобы превратить
    # первые i символов word1 в первые j символов word2
    dp = [[0] * (n + 1) for _ in range(m + 1)]

    # Заполняем первый столбец: чтобы из word1[:i] сделать пустую строку, нужно i удалений
    for i in range(m + 1):
        dp[i][0] = i

    # Заполняем первую строку: чтобы из пустой строки получить word2[:j], нужно j вставок
    for j in range(n + 1):
        dp[0][j] = j

    # Заполняем таблицу динамического программирования
    for i in range(1, m + 1):
        for j in range(1, n + 1):
            # Если текущие символы одинаковы — операция не требуется
            if word1[i - 1] == word2[j - 1]:
                dp[i][j] = dp[i - 1][j - 1]
            else:
                # Иначе выбираем минимальную операцию:
                # 1. Удаление символа (dp[i - 1][j])
                # 2. Вставка символа (dp[i][j - 1])
                # 3. Замена символа (dp[i - 1][j - 1])
                dp[i][j] = 1 + min(
                    dp[i - 1][j],    # удаление
                    dp[i][j - 1],    # вставка
                    dp[i - 1][j - 1] # замена
                )

    # Возвращаем минимальное количество операций для превращения word1 → word2
    return dp[m][n]


# Пример использования
print(min_edit_distance('cat', 'cut'))  # ожидаемый результат: 1


