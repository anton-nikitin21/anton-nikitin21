def num_decodings(S: str) -> int:
    # Если строка пустая или начинается с '0', декодировать нельзя
    if not S or S[0] == '0':
        return 0

    N = len(S)
    dp = [0] * (N + 1)  # dp[i] — количество способов декодирования первых i символов
    dp[0], dp[1] = 1, 1  # базовые случаи: пустая строка и первый символ (не '0')

    # Проходим по строке с позиции 2 до N включительно
    for i in range(2, N + 1):
        one = int(S[i-1:i])    # однозначное число — последний символ
        two = int(S[i-2:i])    # двухзначное число — последние два символа

        # Если однозначное число от 1 до 9 — можно добавить способы из dp[i-1]
        if 1 <= one <= 9:
            dp[i] += dp[i-1]

        # Если двухзначное число от 10 до 26 — можно добавить способы из dp[i-2]
        if 10 <= two <= 26:
            dp[i] += dp[i-2]

    return dp[N]


# -----------------------------------------
# АНАЛИЗ СЛОЖНОСТИ:
#
# Пусть:
#   N — длина строки S
#
# Временная сложность:
# - Проход по строке один раз: O(N)
# - Каждая итерация — константное время операций
# → Итого: O(N)
#
# Пространственная сложность:
# - Массив dp длиной N+1: O(N)
# - Дополнительная память незначительна
# → Итого: O(N)
# -----------------------------------------

# Пример на "226":
# dp[0] = 1 (пустая строка)
# dp[1] = 1 (символ '2' → 'B')
# Для i=2 (строка "22"):
# Последний символ '2' — это 1..9 → dp[2] += dp[1] → dp[2] = 1
# Последние два символа '22' → 10..26 → dp[2] += dp[0] → dp[2] = 2
# Для i=3 (строка "226"):
# Последний символ '6' → 1..9 → dp[3] += dp[2] → dp[3] = 2
# Последние два символа '26' → 10..26 → dp[3] += dp[1] → dp[3] = 3
# Итог:
# Строку "226" можно расшифровать тремя способами:
# "2" "2" "6" → "B" "B" "F"
# "22" "6" → "V" "F"
# "2" "26" → "B" "Z"