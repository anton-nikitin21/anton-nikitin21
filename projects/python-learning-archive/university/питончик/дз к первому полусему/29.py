# Считываем координаты начальной позиции коня
x1 = int(input())  # координата по горизонтали
y1 = int(input())  # координата по вертикали

# Считываем координаты целевой позиции
x2 = int(input())  # координата по горизонтали
y2 = int(input())  # координата по вертикали

# Конь ходит буквой "Г": 2 клетки в одном направлении и 1 клетку в перпендикулярном
# Проверяем оба варианта хода коня
if (abs(x1 - x2) == 2 and abs(y1 - y2) == 1) or (abs(x1 - x2) == 1 and abs(y1 - y2) == 2):
    print("YES")  # Ход возможен
else:
    print("NO")   # Ход невозможен
