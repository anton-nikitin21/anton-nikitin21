def smart_operation():
    # Функция запрашивает два значения у пользователя и либо складывает их как числа,
    # либо объединяет как строки, если хотя бы одно значение нельзя привести к числу

    a = input("Введите первое значение: ")
    # Запрашиваем у пользователя первое значение и сохраняем его как строку

    b = input("Введите второе значение: ")
    # Запрашиваем второе значение и сохраняем его как строку

    # Попробуем преобразовать оба значения в числа
    try:
        a_num = float(a)
        b_num = float(b)
        result = a_num + b_num
        # Если оба значения успешно преобразованы в float, складываем их
    except ValueError:
        # Если хотя бы одно значение не может быть преобразовано в число
        result = a + b
        # Выполняем конкатенацию строк

    print("Операция выполнена")
    # Сообщаем пользователю, что операция выполнена

    return result
    # Возвращаем результат (числовую сумму или объединение строк)


# Пример использования:
res = smart_operation()
print("Результат:", res)
