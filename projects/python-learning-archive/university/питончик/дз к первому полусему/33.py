# Ввод строки от пользователя
text = input("Введите строку текста: ")

# Приводим к нижнему регистру, чтобы не различать 'Python' и 'python'
text = text.lower()

# Удаляем знаки пунктуации вручную (без модуля string)
for symbol in ",.!?;:-()\"'":
    text = text.replace(symbol, "")

# Разбиваем строку на слова по пробелам
words = text.split()

# Создаём множество уникальных слов
unique_words = set(words)

# Определяем количество различных слов
count = len(unique_words)

# Выводим результат
print("Количество различных слов:", count)