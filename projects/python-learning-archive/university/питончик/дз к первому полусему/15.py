def merge_intervals(intervals):
   # Проверяем, если список интервалов пуст, возвращаем пустой список
   if not intervals:
       return []
   # Шаг 1: Сортируем интервалы по начальному значению (start).
   # Для этого используется функция `sort()` и ключ сортировки — первый элемент каждого интервала (start).
   # Например, если интервал [1, 3], то `x[0]` будет 1, и сортировка будет по возрастанию этого значения.
   intervals.sort(key=lambda x: x[0])
   # Шаг 2: Создаем новый список `merged` для хранения объединенных интервалов.
   merged = []
   # Шаг 3: Проходим по каждому интервалу в отсортированном списке `intervals`.
   for interval in intervals:
       # Если список `merged` пуст (это первый интервал) ИЛИ последний добавленный интервал
       # в `merged` не перекрывается с текущим интервалом (т.е. его конец меньше начала текущего интервала),
       # добавляем текущий интервал в список `merged`.
       if not merged or merged[-1][1] < interval[0]:
           merged.append(interval)
       else:
           # Если текущий интервал перекрывается с последним интервалом в `merged`,
           # объединяем их. Это достигается обновлением конца последнего интервала.
           # Мы берем максимальное значение между концом последнего интервала и концом текущего интервала.
           merged[-1][1] = max(merged[-1][1], interval[1])

   # Возвращаем объединенные интервалы.
   return merged

# Пример использования:
intervals = [[1, 8], [2, 6], [8, 10], [13, 16], [16, 19]]
# Вызываем функцию merge_intervals и сохраняем результат в переменную result
result = merge_intervals(intervals)

# Выводим объединенные интервалы
print(result)

