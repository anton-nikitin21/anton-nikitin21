def is_correct_bracket_sequence(text):
    # Функция проверяет, является ли строка text корректной последовательностью круглых скобок

    count = 0  # Счётчик открытых скобок '('

    for ch in text:
        # Проходим по каждому символу строки

        if ch == '(':
            count += 1
            # Если встретили '(', увеличиваем счётчик

        elif ch == ')':
            count -= 1
            # Если встретили ')', уменьшаем счётчик

        # Если количество закрытых скобок превысило количество открытых
        if count < 0:
            return False
            # Последовательность некорректна, возвращаем False

    # После проверки всей строки
    return count == 0
    # Корректно, если все открытые скобки были закрыты
