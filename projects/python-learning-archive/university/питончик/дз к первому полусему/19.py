def f(*a):
    # Функция принимает любое количество аргументов через *a и собирает их в кортеж

    a = list(a)
    # Преобразуем кортеж в список для возможности изменения элементов

    total = 0
    # Инициализируем переменную total для накопления суммы объединений

    while len(a) > 1:
        # Пока в списке больше одного элемента, продолжаем объединять

        a.sort()
        # Сортируем список по возрастанию, чтобы взять два минимальных элемента

        min1 = a.pop(0)
        # Удаляем и сохраняем первый (минимальный) элемент списка

        min2 = a.pop(0)
        # Удаляем и сохраняем второй (минимальный) элемент списка

        s = min1 + min2
        # Суммируем два минимальных числа

        total += s
        # Добавляем сумму к общей накопленной величине total

        a.append(s)
        # Добавляем сумму обратно в список, чтобы участвовать в дальнейших объединениях

    return total
    # Когда в списке останется один элемент, возвращаем общую сумму объединений


# Пример вызова
print(f(3, 5, 10))
# Ожидаемый результат: 26

