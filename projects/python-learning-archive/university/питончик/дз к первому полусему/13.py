def min_jumps(nums):
    # Если длина массива 1, то уже стоим на последнем элементе → 0 прыжков
    if len(nums) <= 1:
        return 0

    jumps = 0          # Количество сделанных прыжков
    current_end = 0    # Правая граница текущего "прыжкового диапазона"
    farthest = 0       # Самая дальняя позиция, достижимая из текущего диапазона

    # Проходим по массиву до предпоследнего элемента
    # (последний не нужен — если мы до него дошли, прыжок уже совершен)
    for i in range(len(nums) - 1):
        # Обновляем самую дальнюю достижимую позицию на текущем шаге
        farthest = max(farthest, i + nums[i])

        # Если достигли конца текущего диапазона
        if i == current_end:
            jumps += 1              # совершаем прыжок
            current_end = farthest  # обновляем границу диапазона

            # Если можем уже достичь конца массива — выходим раньше
            if current_end >= len(nums) - 1:
                break

    # Возвращаем общее количество прыжков
    return jumps


# -----------------------------------------
# АНАЛИЗ СЛОЖНОСТИ:
#
# Пусть:
#   n = len(nums)
#
# Временная сложность:
# - Один проход по массиву (до n-1 элементов)
# - Каждая операция внутри цикла — O(1)
# → Итого: O(n)
#
# Пространственная сложность:
# - Используются только постоянные переменные (jumps, current_end, farthest)
# → Итого: O(1)
# -----------------------------------------
