# Считываем строку чисел, разделённых пробелами, и преобразуем их в список целых чисел
numbers = list(map(int, input().split()))

# Если в списке только один элемент, выводим его как результат
if len(numbers) == 1:
    print(numbers[0])
else:
    result = []          # Список для хранения сумм соседних элементов
    n = len(numbers)     # Длина исходного списка

    for i in range(n):
        # Находим левый сосед
        left = numbers[i - 1]             # Для i=0 это последний элемент (цикличность)

        # Находим правый сосед
        right = numbers[(i + 1) % n]      # Для последнего элемента это первый элемент (цикличность)

        # Суммируем левого и правого соседей и добавляем в результат
        result.append(left + right)

    # Выводим получившийся список сумм соседей, разделяя пробелами
    print(*result)
