def count_typable_words(S: str, BROKEN: str) -> int:
    # Приводим список сломанных клавиш к нижнему регистру и
    # создаем множество для быстрого поиска (O(1) проверка на наличие символа)
    broken = set(BROKEN.lower())  # O(M), где M — длина строки BROKEN

    # Приводим основную строку к нижнему регистру
    S = S.lower()  # O(N), где N — длина строки S

    count = 0               # Счётчик "печатаемых" слов
    word_has_broken = False # Флаг: содержит ли текущее слово сломанные буквы
    in_word = False         # Флаг: находимся ли мы в слове (буквы подряд)

    # Проходим по каждому символу строки S
    for ch in S:
        if ch.isalpha():  # Если буква — часть слова
            if not in_word:
                in_word = True            # Начало нового слова
                word_has_broken = False   # Пока не знаем, есть ли сломанные буквы
            if ch in broken:
                word_has_broken = True    # Нашли сломанную букву в текущем слове
        else:  # Разделитель (пробел, запятая и т.п.)
            if in_word and not word_has_broken:
                count += 1                # Слово было без сломанных букв — учитываем
            in_word = False               # Завершаем текущее слово

    # Обрабатываем последнее слово, если строка не закончилась разделителем
    if in_word and not word_has_broken:
        count += 1

    return count


# -----------------------------------------
# Пусть:
#   N — длина строки S
#   M — длина строки BROKEN
#
# Временная сложность:
# - Приведение S к нижнему регистру → O(N)
# - Приведение BROKEN к нижнему регистру → O(M)
# - Создание множества broken → O(M)
# - Один проход по строке S → O(N), все проверки внутри цикла — O(1)
#
# → Итоговая временная сложность: **O(N)**
#
# Пространственная сложность:
# - Множество broken → O(M)
# - Остальные переменные (count, флаги) → O(1)
#
# → Итоговая пространственная сложность: **O(M)**
# -----------------------------------------
