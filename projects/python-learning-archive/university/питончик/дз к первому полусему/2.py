# АНАЛИЗ СЛОЖНОСТИ:
#
# Пусть:
#   n = длина строки A
#   m = длина строки B
#
# Временная сложность:
# - Один проход по строке A → O(n)
# - Один проход по строке B → O(m)
# - Все операции со словарём → O(1)
# → Итого: O(n + m)
#
# Пространственная сложность:
# - Словарь `freq` хранит частоты букв из A → O(n) (в худшем случае, если все символы разные)
# - Новые копии строк не создаются → экономия памяти
# → Итого: O(n)
