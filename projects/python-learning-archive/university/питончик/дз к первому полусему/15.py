# АНАЛИЗ СЛОЖНОСТИ:
#
# Пусть:
#   n = количество интервалов
#
# Временная сложность:
# - Сортировка интервалов: O(n log n)
# - Один проход по массиву для объединения: O(n)
# → Итого: O(n log n)
#
# Пространственная сложность:
# - Используется новый список merged (в худшем случае — все интервалы)
# → Итого: O(n)
