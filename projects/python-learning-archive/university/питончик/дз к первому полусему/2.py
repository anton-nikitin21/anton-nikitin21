def can_build_strs(A, B):
    # Создаем словарь частот для букв из строки A
    freq = {}

    # Перебираем символы строки A
    for ch in A:
        # Если символ — буква, учитываем его в словаре
        if ch.isalpha():
            ch = ch.lower()
            freq[ch] = freq.get(ch, 0) + 1

    # Проверяем, можно ли составить строку B
    for ch in B:
        # Аналогично — проверяем только буквы
        if ch.isalpha():
            ch = ch.lower()
            # Если буквы нет или закончились её вхождения — нельзя
            if ch not in freq or freq[ch] == 0:
                return 'no'
            # Используем одну букву
            freq[ch] -= 1

    # Все буквы подошли — можно
    return 'yes'


# --- Основная часть программы ---
A = input()
B = input()
print(can_build_strs(A, B))


