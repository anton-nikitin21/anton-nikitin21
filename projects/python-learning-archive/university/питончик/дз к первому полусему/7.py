def to_roman(num: int) -> str:
    # Проверяем, что число в допустимом диапазоне (1–3999)
    if not (0 < num < 4000):
        raise ValueError("Римские цифры поддерживаются только для чисел 1–3999")

    # Сопоставление значений с римскими символами в порядке убывания
    roman_map = [
        (1000, "M"), (900, "CM"), (500, "D"), (400, "CD"),
        (100, "C"), (90, "XC"), (50, "L"), (40, "XL"),
        (10, "X"), (9, "IX"), (5, "V"), (4, "IV"), (1, "I")
    ]

    result = ""  # Результирующая строка с римским числом

    # Проходим по каждой паре (значение, символ)
    for value, symbol in roman_map:
        # Пока число больше или равно текущему значению, добавляем символ и вычитаем значение
        while num >= value:
            result += symbol
            num -= value

    return result


print(to_roman(52))  # Вывод: LII


