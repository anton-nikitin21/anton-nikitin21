def sum_numbers(arr):
    total = 0
    # Инициализируем переменную для хранения суммы

    for item in arr:
        # Перебираем все элементы списка arr

        if isinstance(item, (int, float)):
            # Проверяем, является ли элемент числом (int или float)
            total += item
            # Если да — добавляем к сумме

    return total
    # Возвращаем итоговую сумму всех числовых элементов


def sum_numbers_1(arr):
    total = 0
    # Инициализируем переменную для хранения суммы

    for item in arr:
        # Перебираем все элементы списка arr

        try:
            total += float(item)
            # Пробуем преобразовать элемент в число float
            # Если преобразование успешно — добавляем к сумме

        except (ValueError, TypeError):
            # Если элемент не может быть преобразован (строка, None, список и т. д.)
            continue
            # Просто пропускаем этот элемент

    return total
    # Возвращаем итоговую сумму всех успешно преобразованных значений
