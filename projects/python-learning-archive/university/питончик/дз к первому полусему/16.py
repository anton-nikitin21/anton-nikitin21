def find_even_digit_numbers(N):
   # Определяем основную функцию, которая находит числа от 0 до N с четными цифрами
   # Внутренняя функция для проверки, что каждая цифра числа четная
   def is_all_digits_even(num):
       # Проходим по каждой цифре числа (преобразуем число в строку для удобства)
       for digit in str(num):
           # Если хотя бы одна цифра нечетная (остаток от деления на 2 не равен 0), возвращаем False
           if int(digit) % 2 != 0:
               return False
       # Если цикл завершился и все цифры четные, возвращаем True
       return True
   # Создаем пустой список для хранения чисел, у которых все цифры четные
   result = []
   # Цикл по числам от 0 до N включительно
   for i in range(N + 1):
       # Если число состоит только из четных цифр (проверяем с помощью функции is_all_digits_even)
       if is_all_digits_even(i):
           # Добавляем это число в список результатов
           result.append(i)
   # Преобразуем список чисел в строку, где числа разделены пробелами, и выводим результат
   print(" ".join(map(str, result)))
# Пример использования программы
N = int(input("Введите число N: "))  # Пользователь вводит значение N
find_even_digit_numbers(N)  # Вызываем функцию с введенным значением N


