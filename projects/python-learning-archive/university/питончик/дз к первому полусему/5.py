#
# Пусть:
#   n = длина исходной строки str1
#   m = длина исходной строки str2
#   N = длина нормализованной строки s1 (N ≤ n)
#   M = длина нормализованной строки s2 (M ≤ m)
#   g = gcd(N, M)
#
# Временная сложность:
# 1. normalize(str1) → O(n)
# 2. normalize(str2) → O(m)
# 3. Сравнение s1 + s2 и s2 + s1 → O(N + M)
# 4. Вычисление НОД (алгоритм Евклида) → O(log(min(N, M)))
# 5. Взятие среза s1[:g] → O(g), где g ≤ min(N, M)
#
# Так как g ≤ min(N, M), а N ≤ n, M ≤ m, то O(g) ∈ O(n + m)
