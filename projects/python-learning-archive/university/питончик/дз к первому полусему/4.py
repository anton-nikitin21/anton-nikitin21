# АНАЛИЗ СЛОЖНОСТИ:
#
# Пусть:
#   m = длина строки word1
#   n = длина строки word2
#
# Временная сложность:
# - Мы заполняем таблицу dp размером (m+1) × (n+1)
# - Каждая ячейка вычисляется за O(1)
# → Итого: O(m * n)
#
# Пространственная сложность:
# - Таблица dp занимает (m+1) × (n+1) элементов
# - Дополнительная память для переменных незначительна
# → Итого: O(m * n)
# -----------------------------------------


