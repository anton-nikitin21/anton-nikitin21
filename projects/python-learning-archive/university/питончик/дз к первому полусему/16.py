# АНАЛИЗ СЛОЖНОСТИ:
#
# Пусть:
#   N — верхняя граница диапазона.
#   k — среднее количество цифр в числе (≈ log10(N)).
#
# Временная сложность:
# - Для каждого числа (N + 1 итераций) мы проверяем все его цифры.
# - Проверка каждой цифры занимает O(k).
# → Итого: O(N * k) ≈ O(N * log N)
#
# Пространственная сложность:
# - Используется список result, который в худшем случае может содержать все числа от 0 до N.
# → Итого: O(N)
