#
# Пусть:
#   n — количество слов
#   k — средняя длина слова
#
# Временная сложность:
# - Проход по каждому слову: O(n)
# - Для каждого слова:
#     - Удаление пробелов и перевод в нижний регистр: O(k)
#     - Подсчет частот букв: O(k)
#     - Создание ключа из фиксированного массива: O(1)
# - Добавление в словарь групп: в среднем O(1)
# → Итого: O(n * k)
#
# Пространственная сложность:
# - Массив частот — фиксированного размера: O(1)
# - Словарь групп хранит все слова и ключи: O(n * k)
# → Итого: O(n * k)
