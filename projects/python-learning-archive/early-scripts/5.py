import numpy as np  # подключаем библиотеку для работы с числами и массивами

# 1. Определяем функцию, подынтегральное выражение
# f(x) = 0.3x - 6x + 17 = -5.7x + 17
def f(x):
    return 0.3 * x**2 - 6 * x + 17

# 2. Задаём пределы интегрирования
a = 2   # нижний предел
b = 4   # верхний предел

# 3. Количество случайных точек (чем больше — тем точнее)
N = 100000

# 4. Генерируем N случайных значений x в диапазоне [a, b]
x_random = np.random.uniform(a, b, N)

# 5. Вычисляем значение функции в каждой случайной точке
y_values = f(x_random)

# 6. Среднее значение функции
mean_f = np.mean(y_values)

# 7. Приближённый интеграл по формуле Монте-Карло
integral_mc = (b - a) * mean_f

print("Приближённое значение интеграла (Монте-Карло):", integral_mc)