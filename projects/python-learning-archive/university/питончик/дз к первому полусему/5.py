def gcd_of_strings(str1: str, str2: str) -> str:
    # --- Шаг 1: нормализация строк ---
    # Оставляем только буквы и приводим к нижнему регистру
    def normalize(s: str) -> str:
        result = ""
        for ch in s:
            if ch.isalpha():           # Убираем всё, кроме букв
                result += ch.lower()   # Приводим к нижнему регистру
        return result

    # Нормализуем обе строки
    s1 = normalize(str1)
    s2 = normalize(str2)

    # --- Шаг 2: проверка на "общую строковую основу" ---
    # Если строки не являются повторениями одной и той же подстроки,
    # то не может быть общего делителя строк
    if s1 + s2 != s2 + s1:
        return ""

    # --- Шаг 3: находим НОД длин нормализованных строк ---
    def gcd(a: int, b: int) -> int:
        # Алгоритм Евклида для НОД
        while b != 0:
            a, b = b, a % b
        return a

    g = gcd(len(s1), len(s2))  # Наибольший общий делитель длин строк

    # --- Шаг 4: возвращаем общую подстроку длины НОД ---
    return s1[:g]


# Пример использования
print(gcd_of_strings("ABCabc123", "abcabc"))  # Ожидаемый результат: "abc"

