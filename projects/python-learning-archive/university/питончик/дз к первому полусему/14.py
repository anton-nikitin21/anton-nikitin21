def group_anagrams_1(words):
    groups = {}  # Создаем словарь для групп анаграмм: ключ — "подпись" слова, значение — список слов с такой подписью

    for word in words:
        # Удаляем пробелы из слова и приводим его к нижнему регистру,
        # чтобы игнорировать регистр и пробелы при сравнении анаграмм
        clean_word = word.replace(" ", "").lower()

        freq = {}  # Создаем словарь для подсчета частот символов в слове
        for ch in clean_word:
            # Для каждого символа увеличиваем счетчик его встречаемости
            freq[ch] = freq.get(ch, 0) + 1

        # Создаем ключ — кортеж отсортированных пар (символ, количество),
        # чтобы ключ был хэшируемым и одинаковым для анаграмм (независимо от порядка букв)
        key = tuple(sorted(freq.items()))

        # Если такой ключ уже есть, добавляем текущее слово в соответствующую группу
        if key in groups:
            groups[key].append(word)  # Добавляем исходное слово (с оригинальным регистром и пробелами)
        else:
            # Если ключа еще нет — создаем новую группу с этим словом
            groups[key] = [word]

    # Возвращаем список всех сгруппированных анаграмм (списки слов)
    return list(groups.values())

# -----------------------------------------
# Пусть:
#   n — количество слов
#   k — средняя длина слова (включая пробелы)
#
# Временная сложность:
# - Для каждого слова:
#     - Удаление пробелов и преобразование регистра — O(k)
#     - Подсчет частот символов — O(k)
#     - Сортировка частотных пар (в худшем случае до k уникальных символов) — O(k log k)
#     - Добавление в словарь — O(1) в среднем
# - Итог на слово: O(k log k)
# - Для всех слов: O(n * k log k)
#
# Пространственная сложность:
# - Частотный словарь для одного слова — O(k)
# - Ключи словаря групп — до O(n * k) (хранение ключей для всех слов)
# - Значения словаря (списки слов) — O(n * k) (хранение всех слов)
#
# Итог: O(n * k) по памяти
# -----------------------------------------


def group_anagrams(words):
    groups = {}  # Словарь для хранения групп анаграмм.
                 # Ключ — кортеж частот букв, значение — список слов, подходящих под этот ключ.

    for word in words:
        # Удаляем все пробелы из слова и приводим его к нижнему регистру,
        # чтобы сравнение было нечувствительно к регистру и пробелам.
        clean_word = word.replace(" ", "").lower()

        # Создаем список длиной 32 для подсчёта частот букв русского алфавита 'а'–'я'.
        # Индексы 0..31 соответствуют буквам от 'а' до 'я' по порядку.
        freq = [0] * 32

        for ch in clean_word:
            # Проверяем, входит ли символ в диапазон русских букв 'а'–'я'.
            if 'а' <= ch <= 'я':
                # Вычисляем индекс буквы, вычитая код 'а' из кода текущего символа,
                # и увеличиваем счетчик для этой буквы.
                freq[ord(ch) - ord('а')] += 1
            else:
                # Символ не относится к русскому алфавиту — пропускаем его.
                pass

        # Преобразуем массив частот в кортеж, чтобы использовать его в качестве ключа словаря.
        # Кортеж является неизменяемым и хэшируемым, в отличие от списка.
        # Все анаграммы будут иметь одинаковый ключ, потому что у них одинаковый набор букв с одинаковыми частотами.
        key = tuple(freq)

        # Проверяем, есть ли уже такая группа с этим ключом.
        if key in groups:
            # Если есть — добавляем текущее исходное слово (с пробелами и регистром, как было изначально) в группу.
            groups[key].append(word)
        else:
            # Если нет — создаем новую группу с этим словом.
            groups[key] = [word]

    # Возвращаем список групп анаграмм (каждая группа — список слов).
    return list(groups.values())

