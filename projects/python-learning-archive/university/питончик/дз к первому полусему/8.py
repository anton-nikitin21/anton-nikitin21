def multiply_strings(A, B):
    # Если одно из чисел равно "0", результат всегда "0"
    if A == "0" or B == "0":
        return "0"

    N, M = len(A), len(B)
    # Создаем массив для хранения результата длиной N+M (максимальная длина произведения)
    result = [0] * (N + M)

    # Умножаем "в столбик" — по цифрам справа налево
    for i in range(N - 1, -1, -1):
        for j in range(M - 1, -1, -1):
            mul = int(A[i]) * int(B[j])  # произведение отдельных цифр
            sum_ = mul + result[i + j + 1]  # учитываем перенос из предыдущих вычислений

            result[i + j + 1] = sum_ % 10   # текущая цифра результата
            result[i + j] += sum_ // 10     # перенос в старший разряд

    # Преобразуем массив цифр в строку, убираем ведущие нули
    result_str = ''.join(map(str, result)).lstrip('0')
    return result_str


# -----------------------------------------
# АНАЛИЗ СЛОЖНОСТИ:
#
# Пусть:
#   N = длина строки A
#   M = длина строки B
#
# Временная сложность:
# - Вложенный цикл: проходим по каждой паре цифр → O(N * M)
# - Внутренние операции (умножение, сложение, присвоение) — O(1)
# - Преобразование результата в строку — O(N + M)
# → Итого: O(N * M)
#
# Пространственная сложность:
# - Массив result длиной N + M — O(N + M)
# - Дополнительная память для переменных незначительна
# → Итого: O(N + M)
# -----------------------------------------


