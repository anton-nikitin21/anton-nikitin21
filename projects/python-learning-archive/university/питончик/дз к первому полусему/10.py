def matches_pattern(P: str, S: str) -> bool:
    # Разбиваем строку S на слова по пробелам
    words = S.split()

    # Если количество символов в шаблоне не совпадает с количеством слов — нет соответствия
    if len(P) != len(words):
        return False

    p_to_w = {}  # отображение: символ шаблона → слово
    w_to_p = {}  # обратное отображение: слово → символ шаблона

    # Проходим по парам (символ, слово)
    for ch, word in zip(P, words):
        if ch in p_to_w:
            # Если символ уже связан, но с другим словом — конфликт
            if p_to_w[ch] != word:
                return False
        elif word in w_to_p:
            # Если слово уже связано, но с другим символом — конфликт
            if w_to_p[word] != ch:
                return False
        else:
            # Связываем символ с новым словом и наоборот
            p_to_w[ch] = word
            w_to_p[word] = ch

    # Все пары прошли проверку — шаблон совпадает
    return True


# -----------------------------------------
# АНАЛИЗ СЛОЖНОСТИ:
#
# Пусть:
#   n — длина строки P (количество символов)
#   m — длина строки S (в символах)
#
# Временная сложность:
# - Разделение строки S на слова: O(m)
# - Проход по zip(P, words): максимум n итераций
#   - Все операции со словарями (in, [], =): O(1)
# Почему говорим O(m):
# В условии задачи M ≥ n (так как строка S содержит n слов + пробелы)
# Поэтому m + n ≤ m + m = 2m = O(m)
# Доминирующая операция - обработка строки S
# → Итого: O(m)
#
# Пространственная сложность:
# - Список слов: O(n)
# - Словари p_to_w и w_to_p: максимум n пар → O(n)
# → Итого: O(n)
